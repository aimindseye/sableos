DOC="$REPO/docs/titan2/N1B_PHYSICAL_UX_ACCEPTANCE_READINESS.md"
FAILURES=0
FIRST_FAILURE=""

say() {
  printf '%s\n' "$1"
}

record_failure() {
  NAME="$1"
  DETAIL="$2"
  FAILURES=$((FAILURES + 1))
  if [ -z "$FIRST_FAILURE" ]; then
    FIRST_FAILURE="$NAME"
  fi
  say "$NAME=FAIL"
  say "$DETAIL"
}

pass() {
  say "$1=PASS"
}

require_marker() {
  NAME="$1"
  MARKER="$2"
  if grep -Fq "$MARKER" "$DOC" 2>/dev/null; then
    pass "$NAME"
  else
    record_failure "$NAME" "MISSING_MARKER=$MARKER"
  fi
}

