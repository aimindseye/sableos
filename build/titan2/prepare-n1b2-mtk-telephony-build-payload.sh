#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ANDROID_SRC="${ANDROID_SRC:-}"
STOCK_ROOT="${STOCK_ROOT:-}"
EVIDENCE_DIR="${EVIDENCE_DIR:-/tmp/SABLE_N1B2_MTK_BUILD_PAYLOAD_$(date -u +%Y%m%dT%H%M%SZ)}"
PAYLOAD_REL="vendor/sable/n1b2/mtk-telephony-payload"
COPY_PAYLOAD="YES"

usage() {
  cat >&2 <<'EOF'
Usage:
  build/titan2/prepare-n1b2-mtk-telephony-build-payload.sh \
    --android-src DIR \
    --stock-root DIR \
    [--evidence-dir DIR]

Stages the local stock-derived Titan 2 MTK telephony/IMS payload into the
Android source tree under vendor/sable/n1b2/mtk-telephony-payload and injects a
generated product makefile include into vendor/sable/n1b2/sable_n1b2_product_profile.mk.

This script copies proprietary payload files only into the local Android build
workspace. It does not commit payload binaries to Git, does not flash, does not
use adb, and does not use fastboot.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --android-src) ANDROID_SRC="$2"; shift 2 ;;
    --android-src=*) ANDROID_SRC="${1#*=}"; shift ;;
    --stock-root) STOCK_ROOT="$2"; shift 2 ;;
    --stock-root=*) STOCK_ROOT="${1#*=}"; shift ;;
    --evidence-dir) EVIDENCE_DIR="$2"; shift 2 ;;
    --evidence-dir=*) EVIDENCE_DIR="${1#*=}"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "UNKNOWN_ARG=$1" >&2; usage; exit 2 ;;
  esac
done

[[ -n "$ANDROID_SRC" && -d "$ANDROID_SRC" ]] || { echo "N1B2_MTK_BUILD_PAYLOAD=FAIL_ANDROID_SRC_REQUIRED path=$ANDROID_SRC"; exit 2; }
[[ -n "$STOCK_ROOT" && -d "$STOCK_ROOT" ]] || { echo "N1B2_MTK_BUILD_PAYLOAD=FAIL_STOCK_ROOT_REQUIRED path=$STOCK_ROOT"; exit 2; }

ANDROID_SRC="$(cd "$ANDROID_SRC" && pwd)"
STOCK_ROOT="$(cd "$STOCK_ROOT" && pwd)"
mkdir -p "$EVIDENCE_DIR"
EVIDENCE_DIR="$(cd "$EVIDENCE_DIR" && pwd)"

PROFILE_MK="$ANDROID_SRC/vendor/sable/n1b2/sable_n1b2_product_profile.mk"
[[ -f "$PROFILE_MK" ]] || { echo "N1B2_MTK_BUILD_PAYLOAD=FAIL_PROFILE_MK path=$PROFILE_MK"; exit 66; }

PAYLOAD_ROOT="$ANDROID_SRC/$PAYLOAD_REL"
PAYLOAD_FILES="$PAYLOAD_ROOT/files"
PAYLOAD_MK="$PAYLOAD_ROOT/sable_n1b2_mtk_telephony_payload.mk"
INCLUDE_LINE="$(call inherit-product-if-exists, $PAYLOAD_REL/sable_n1b2_mtk_telephony_payload.mk)"
mkdir -p "$PAYLOAD_FILES"

STAGE_EVIDENCE="$EVIDENCE_DIR/stage"
bash "$ROOT/build/titan2/stage-n1b2-mtk-telephony-payload.sh" \
  --stock-root "$STOCK_ROOT" \
  --evidence-dir "$STAGE_EVIDENCE" \
  --stage-dir "$PAYLOAD_FILES" \
  --copy-payload "$COPY_PAYLOAD"

MANIFEST="$STAGE_EVIDENCE/pr208-stock-mtk-telephony-payload-manifest.tsv"
[[ -f "$MANIFEST" ]] || { echo "N1B2_MTK_BUILD_PAYLOAD=FAIL_MANIFEST_MISSING path=$MANIFEST"; exit 67; }

target_for_rel() {
  local rel="$1"
  case "$rel" in
    system_ext/*) printf '$(TARGET_COPY_OUT_SYSTEM_EXT)/%s' "${rel#system_ext/}" ;;
    product/*) printf '$(TARGET_COPY_OUT_PRODUCT)/%s' "${rel#product/}" ;;
    system/*) printf '$(TARGET_COPY_OUT_SYSTEM)/%s' "${rel#system/}" ;;
    *) echo "UNSUPPORTED_REL=$rel" >&2; return 1 ;;
  esac
}

{
  echo "# Auto-generated by build/titan2/prepare-n1b2-mtk-telephony-build-payload.sh"
  echo "# Source stock root: $STOCK_ROOT"
  echo "# Evidence dir: $EVIDENCE_DIR"
  echo ""
  echo "PRODUCT_COPY_FILES += \\" 

  tail -n +2 "$MANIFEST" | while IFS=$'\t' read -r rel src kind sha size copied; do
    [[ -n "$rel" ]] || continue
    target="$(target_for_rel "$rel")"
    echo "    $PAYLOAD_REL/files/$rel:$target \\" 
  done

  echo ""
} > "$PAYLOAD_MK"

if ! grep -Fq "$INCLUDE_LINE" "$PROFILE_MK"; then
  {
    echo ""
    echo "# N1B2 MTK telephony/IMS payload; generated locally from stock firmware."
    echo "$INCLUDE_LINE"
  } >> "$PROFILE_MK"
fi

MARKERS="$EVIDENCE_DIR/n1b2-mtk-build-payload-markers.txt"
{
  echo "N1B2_MTK_BUILD_PAYLOAD=PASS"
  echo "N1B2_MTK_BUILD_PAYLOAD_ANDROID_SRC=$ANDROID_SRC"
  echo "N1B2_MTK_BUILD_PAYLOAD_STOCK_ROOT=$STOCK_ROOT"
  echo "N1B2_MTK_BUILD_PAYLOAD_ROOT=$PAYLOAD_ROOT"
  echo "N1B2_MTK_BUILD_PAYLOAD_MK=$PAYLOAD_MK"
  echo "N1B2_MTK_BUILD_PAYLOAD_PROFILE_MK=$PROFILE_MK"
  echo "N1B2_MTK_BUILD_PAYLOAD_PROFILE_INCLUDE=PASS"
  echo "N1B2_MTK_BUILD_PAYLOAD_PRODUCT_COPY_FILES=YES"
  echo "N1B2_MTK_BUILD_PAYLOAD_VENDOR_PARTITION_COPY=NO"
  echo "N1B2_MTK_BUILD_PAYLOAD_PROPRIETARY_PAYLOAD_COMMITTED=NO"
  echo "N1B2_MTK_BUILD_PAYLOAD_ADB_USED=NO"
  echo "N1B2_MTK_BUILD_PAYLOAD_FASTBOOT_USED=NO"
  echo "N1B2_MTK_BUILD_PAYLOAD_FLASH_USED=NO"
} | tee "$MARKERS"

echo "PAYLOAD_MANIFEST=$MANIFEST"
echo "PAYLOAD_MK=$PAYLOAD_MK"
echo "PAYLOAD_ROOT=$PAYLOAD_ROOT"
echo "MARKERS=$MARKERS"
