record_failure() {
  NAME="$1"
  DETAIL="$2"
  FAILURES=$((FAILURES + 1))
  if [ -z "$FIRST_FAILURE" ]; then
    FIRST_FAILURE="$NAME"
  fi
  say "$NAME=FAIL"
  say "$DETAIL"
}

pass() {
  say "$1=PASS"
}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$REPO/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    record_failure "$NAME" "MISSING_PATH=$PATH_VALUE"
  fi
}

require_marker() {
  NAME="$1"
  MARKER="$2"
