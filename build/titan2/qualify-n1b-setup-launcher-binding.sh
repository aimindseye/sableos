#!/usr/bin/env bash

REPO="${REPO:-$(pwd)}"
DOC="$REPO/docs/titan2/N1B_SETUP_LAUNCHER_BINDING_READINESS.md"
FAILURES=0
FIRST_FAILURE=""

say() {
  printf '%s\n' "$1"
}

record_failure() {
  NAME="$1"
  DETAIL="$2"
  FAILURES=$((FAILURES + 1))
  if [ -z "$FIRST_FAILURE" ]; then
    FIRST_FAILURE="$NAME"
  fi
  say "$NAME=FAIL"
  say "$DETAIL"
}

pass() {
  say "$1=PASS"
}

require_marker() {
  NAME="$1"
  MARKER="$2"
  if grep -Fq "$MARKER" "$DOC" 2>/dev/null; then
    pass "$NAME"
  else
    record_failure "$NAME" "MISSING_MARKER=$MARKER"
  fi
}

say "===== N1B SETUP LAUNCHER BINDING QUALIFIER ====="
say "REPO=$REPO"
say "DOC=$DOC"
say "SOURCE_MUTATION_AUTHORIZED=NO"
say "BUILD_AUTHORIZED=NO"
say "IMAGE_BUILD_AUTHORIZED=NO"
say "DEVICE_CONTACT_AUTHORIZED=NO"
say "FLASH_AUTHORIZED=NO"
say "ADB_COMMANDS_RUN=NO"
say "FASTBOOT_COMMANDS_RUN=NO"
say "PUBLIC_RELEASE=NO"

if [ ! -f "$DOC" ]; then
  record_failure "N1B_SETUP_LAUNCHER_BINDING_DOC" "MISSING_PATH=$DOC"
else
  pass "N1B_SETUP_LAUNCHER_BINDING_DOC"
fi

if [ "$FAILURES" -eq 0 ]; then
  require_marker "N1B_SETUPWIZARD2_OWNER" \
    "GRAPHENEOS_SETUPWIZARD2_UPSTREAM_OWNER_FOUND=YES"
  require_marker "N1B_PIXEL_SETUP_PRESERVED" \
    "PIXEL_GRAPHENE_SETUPWIZARD2_BASE_PRESERVED=YES"
  require_marker "N1B_TITAN_SETUP_EXTENSION" \
    "TITAN_KEYBOARD_FIRST_SETUP_EXTENSION_REQUIRED=YES"
  require_marker "N1B_CRITICAL_TEXT_ENTRY" \
    "CRITICAL_TEXT_ENTRY_TEST_REQUIRED=YES"
  require_marker "N1B_SOFTWARE_KEYBOARD_FALLBACK" \
    "SOFTWARE_KEYBOARD_FALLBACK_REQUIRED=YES"
  require_marker "N1B_SABLE_START_BINDING" \
    "SABLE_START_KEYBOARD_FIRST_BINDING_REQUIRED=YES"
  require_marker "N1B_PANTHER_HOME_PROTECTED" \
    "PANTHER_TOUCH_FIRST_HOME_BEHAVIOR_PROTECTED=YES"
  require_marker "N1B_NO_IMAGE" \
    "N1B_PHASE_05_DOES_NOT_AUTHORIZE_IMAGE_BUILD=YES"
  require_marker "N1B_NO_FLASH" \
    "N1B_PHASE_05_DOES_NOT_AUTHORIZE_FLASH=YES"
fi

say "===== N1B SETUP LAUNCHER BINDING RESULT ====="
say "FAILURES=$FAILURES"
if [ -n "$FIRST_FAILURE" ]; then
  say "FIRST_FAILURE=$FIRST_FAILURE"
fi

if [ "$FAILURES" -eq 0 ]; then
  say "N1B_SETUP_LAUNCHER_BINDING=PASS"
  exit 0
fi

say "N1B_SETUP_LAUNCHER_BINDING=FAIL"
exit 1
