#!/usr/bin/env bash

ROOT="${1:-.}"
FAILURES=0

say() {
  printf '%s\n' "$1"
}

pass() {
  say "$1=PASS"
}

fail() {
  say "$1=FAIL"
  FAILURES=$((FAILURES + 1))
}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$ROOT/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_PATH=$PATH_VALUE"
  fi
}

require_marker() {
  NAME="$1"
  PATH_VALUE="$2"
  MARKER="$3"
  if grep -Fq "$MARKER" "$ROOT/$PATH_VALUE" 2>/dev/null; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_MARKER=$MARKER"
    say "IN_FILE=$PATH_VALUE"
  fi
}

say "===== TITAN2 CENTRAL FLASH GUARD CONTRACT ====="
say "ROOT=$ROOT"
say "SOURCE_MUTATION_AUTHORIZED=NO"
say "IMAGE_BUILD_AUTHORIZED=NO"
say "DEVICE_CONTACT_AUTHORIZED=NO"
say "FLASH_AUTHORIZED=NO"
say "ADB_COMMANDS_RUN=NO"
say "FASTBOOT_COMMANDS_RUN=NO"

DEVICE="build/devices/titan2.sh"
PREPARE="build/titan2/prepare-n0-n1-flash-plan.sh"
LEDGER="docs/titan2/N0_N1_FLASH_PLAN_LEDGER.md"
REGRESSION_LEDGER="build/TITAN2_FLASH_REGRESSIONS.tsv"
REGRESSION_GATE="build/gates/titan2-flash-regression-contract.py"
REGRESSION_POLICY="docs/titan2/TITAN2_FLASH_REGRESSION_POLICY.md"
MODE_HELPER="build/titan2/titan2-flash-mode.sh"
MODE_SELFTEST="build/titan2/tests/test-titan2-flash-mode.sh"

require_file "TITAN2_DEVICE_ADAPTER" "$DEVICE"
require_file "TITAN2_FLASH_PLAN_PREPARE_SCRIPT" "$PREPARE"
require_file "TITAN2_FLASH_PLAN_LEDGER_DOC" "$LEDGER"
require_file "TITAN2_FLASH_REGRESSION_LEDGER" "$REGRESSION_LEDGER"
require_file "TITAN2_FLASH_REGRESSION_GATE" "$REGRESSION_GATE"
require_file "TITAN2_FLASH_REGRESSION_POLICY" "$REGRESSION_POLICY"
require_file "TITAN2_FLASH_MODE_HELPER" "$MODE_HELPER"
require_file "TITAN2_FLASH_MODE_SELFTEST" "$MODE_SELFTEST"

require_marker "TITAN2_FLASH_EXECUTION_BLOCKED" "$DEVICE" "SABLE_DEVICE_FLASH_SUPPORTED=NO"
require_marker "TITAN2_PRESERVED_DATA_FLASH_BLOCKED" "$DEVICE" "SABLE_DEVICE_PRESERVED_DATA_FLASH_SUPPORTED=NO"
require_marker "TITAN2_GSI_ARTIFACT_KIND" "$DEVICE" "SABLE_DEVICE_ARTIFACT_KINDS=\"gsi-system-image\""
require_marker "TITAN2_FLASH_PLAN_SUPPORTED" "$DEVICE" "SABLE_DEVICE_FLASH_PLAN_SUPPORTED=YES"
require_marker "TITAN2_WRITE_CAPABLE_SCRIPT_BLOCKED" "$DEVICE" "TITAN2_WRITE_CAPABLE_SCRIPT_ALLOWED=NO"
require_marker "TITAN2_FASTBOOT_BOOT_UNSUPPORTED" "$DEVICE" "TITAN2_FASTBOOT_BOOT_SUPPORTED=NO"
require_marker "TITAN2_DSU_UNAVAILABLE" "$DEVICE" "TITAN2_DSU_AVAILABLE=NO"
require_marker "TITAN2_PREPARE_SCRIPT_INTEGRATED" "$DEVICE" "prepare-n0-n1-flash-plan.sh"
require_marker "TITAN2_FLASH_REGRESSION_HELPER" "$DEVICE" "titan2_flash_regression_preflight()"
require_marker "TITAN2_FLASH_REGRESSION_GATE_WIRED" "$DEVICE" "build/gates/titan2-flash-regression-contract.py"
require_marker "TITAN2_FLASH_REGRESSION_POLICY_BLOCK" "$DEVICE" "TITAN2_STANDARD_FLASH_POLICY=BLOCKED_FLASH_REGRESSION"
require_marker "TITAN2_FLASH_REGRESSION_PLAN_BLOCK" "$DEVICE" "TITAN2_FLASH_PLAN=BLOCKED_FLASH_REGRESSION"
require_marker "TITAN2_FLASH_MODE_HELPER_WIRED" "$DEVICE" "TITAN2_FLASH_MODE_HELPER="
require_marker "TITAN2_FLASH_MODE_GATE_WIRED" "$DEVICE" "titan2_ensure_fastbootd_mode"
require_marker "TITAN2_FLASH_MODE_ANDROID_TRANSITION" "$MODE_HELPER" "ANDROID_ADB_TO_BOOTLOADER_FASTBOOT"
require_marker "TITAN2_FLASH_MODE_BOOTLOADER_TRANSITION" "$MODE_HELPER" "BOOTLOADER_FASTBOOT_TO_FASTBOOTD"
require_marker "TITAN2_FLASH_MODE_FASTBOOTD_REUSE" "$MODE_HELPER" "NONE_ALREADY_FASTBOOTD"
require_marker "TITAN2_FLASH_MODE_RECOVERY_BLOCK" "$MODE_HELPER" "BLOCKED_RECOVERY_MANUAL_REVIEW_REQUIRED"
require_marker "TITAN2_FLASH_MODE_BOUNDED_TIMEOUT" "$MODE_HELPER" "TITAN2_MODE_COMMAND_TIMEOUT_SECONDS"
require_marker "TITAN2_FLASH_MODE_SELFTEST_PASS" "$MODE_SELFTEST" "TITAN2_FLASH_MODE_SELFTEST=PASS"

require_marker "PREPARE_NO_DEVICE_CONTACT" "$PREPARE" "DEVICE_CONTACT_AUTHORIZED=NO"
require_marker "PREPARE_NO_FASTBOOT" "$PREPARE" "FASTBOOT_COMMANDS_RUN=NO"
require_marker "PREPARE_NO_FLASH" "$PREPARE" "FLASH_AUTHORIZED=NO"
require_marker "PREPARE_REQUIRES_RESTORE_REPORT" "$PREPARE" "TITAN2_FLASH_PLAN=FAIL_RESTORE_REPORT"
require_marker "PREPARE_REQUIRES_FASTBOOTD_PREFLIGHT" "$PREPARE" "TITAN2_FLASH_PLAN=FAIL_FASTBOOTD_PREFLIGHT"
require_marker "PREPARE_REQUIRES_SNAPSHOT_NONE" "$PREPARE" "FAIL_SNAPSHOT_UPDATE_STATUS"
require_marker "PREPARE_REQUIRES_AVB_ACTION" "$PREPARE" "FAIL_AVB_ACTION"
require_marker "PREPARE_REQUIRES_USERDATA_POLICY" "$PREPARE" "FAIL_USERDATA_POLICY"
require_marker "PREPARE_NO_WRITE_RESULT" "$PREPARE" "TITAN2_FLASH_PLAN=PASS_PREPARED_NO_WRITE"

require_marker "LEDGER_PIXEL_ASSUMPTION_BLOCK" "$LEDGER" "PIXEL_FASTBOOT_ASSUMPTIONS_ALLOWED=NO"
require_marker "LEDGER_PANTHER_ARTIFACT_BLOCK" "$LEDGER" "PANTHER_ARTIFACT_FLASH_TO_TITAN2_ALLOWED=NO"
require_marker "LEDGER_WRITE_SCRIPT_BLOCK" "$LEDGER" "WRITE_CAPABLE_SCRIPT_ALLOWED=NO"

if [ "$FAILURES" -eq 0 ]; then
  python3 "$ROOT/$REGRESSION_GATE" || {
    say "TITAN2_FLASH_REGRESSION_STATIC=FAIL"
    exit 1
  }
  say "TITAN2_FLASH_REGRESSION_STATIC=PASS"
  say "TITAN2_CENTRAL_FLASH_GUARD_CONTRACT=PASS"
  exit 0
fi

say "TITAN2_CENTRAL_FLASH_GUARD_CONTRACT=FAIL"
say "FAILURES=$FAILURES"
exit 1
