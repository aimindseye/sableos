}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$ROOT/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_PATH=$PATH_VALUE"
  fi
}

