#!/usr/bin/env bash

ROOT="${1:-.}"
FAILURES=0

say() {
  printf '%s\n' "$1"
}

pass() {
  say "$1=PASS"
}

fail() {
  say "$1=FAIL"
  FAILURES=$((FAILURES + 1))
}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$ROOT/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_PATH=$PATH_VALUE"
  fi
}

require_marker() {
  NAME="$1"
  PATH_VALUE="$2"
  MARKER="$3"
  if grep -Fq "$MARKER" "$ROOT/$PATH_VALUE" 2>/dev/null; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_MARKER=$MARKER"
    say "IN_FILE=$PATH_VALUE"
  fi
}

say "===== N1B PHYSICAL UX ACCEPTANCE READINESS CONTRACT ====="
say "ROOT=$ROOT"
say "SOURCE_MUTATION_AUTHORIZED=NO"
say "BUILD_AUTHORIZED=NO"
say "IMAGE_BUILD_AUTHORIZED=NO"
say "DEVICE_CONTACT_AUTHORIZED=NO"
say "FLASH_AUTHORIZED=NO"
say "ADB_COMMANDS_RUN=NO"
say "FASTBOOT_COMMANDS_RUN=NO"
say "PUBLIC_RELEASE=NO"
say "PRODUCTION_SIGNING=NO"

DOC="docs/titan2/N1B_PHYSICAL_UX_ACCEPTANCE_READINESS.md"
QUALIFIER="build/titan2/qualify-n1b-physical-ux-readiness.sh"
SELF="build/gates/n1b-physical-ux-readiness-contract.sh"

require_file "N1B_PHYSICAL_UX_DOC" "$DOC"
require_file "N1B_PHYSICAL_UX_QUALIFIER" "$QUALIFIER"
require_file "N1B_PHYSICAL_UX_CONTRACT" "$SELF"

require_marker "DOC_READINESS_MARKER" "$DOC" \
  "N1B_PHYSICAL_UX_ACCEPTANCE_READINESS=YES"
require_marker "DOC_PLATFORM_SABLE_TRACEABILITY" "$DOC" \
  "N1B_PLATFORM_SABLE_DESIGN_TRACEABILITY=YES"
require_marker "DOC_DEVICE_TRACEABILITY" "$DOC" \
  "N1B_DEVICE_SABLE_TITAN2_TRACEABILITY=YES"
require_marker "DOC_OPEN_ISSUE_TRACEABILITY" "$DOC" \
  "N1B_OPEN_ISSUE_TRACEABILITY=YES"
require_marker "DOC_MUST_INCLUDE_SCOPE" "$DOC" \
  "N1B_MUST_INCLUDE_SETUP_WIZARD_PHYSICAL_KEYBOARD_CHECK=YES"
require_marker "DOC_POLICY_GATE_SCOPE" "$DOC" \
  "N1B_POLICY_GATE_KF1_KF2_KEYBOARD_CONTRACTS=YES"
require_marker "DOC_R7E_SUBSTRATE" "$DOC" \
  "N1B_R7E_ANDROID16_RESTLESS_SUBSTRATE_REQUIRED=YES"
require_marker "DOC_N0B_DEVIATIONS" "$DOC" \
  "N1B_N0B_KNOWN_DEVIATIONS_RECORDED=YES"
require_marker "DOC_NO_DEVICE" "$DOC" \
  "N1B_PHASE_06_DOES_NOT_CONTACT_DEVICE=YES"
require_marker "DOC_NO_FLASH" "$DOC" \
  "N1B_PHASE_06_DOES_NOT_AUTHORIZE_FLASH=YES"
require_marker "DOC_NO_IMAGE" "$DOC" \
  "N1B_PHASE_06_DOES_NOT_AUTHORIZE_IMAGE_BUILD=YES"

require_marker "QUALIFIER_NO_BUILD" "$QUALIFIER" \
  "BUILD_AUTHORIZED=NO"
require_marker "QUALIFIER_NO_DEVICE" "$QUALIFIER" \
  "DEVICE_CONTACT_AUTHORIZED=NO"
require_marker "QUALIFIER_NO_FLASH" "$QUALIFIER" \
  "FLASH_AUTHORIZED=NO"
require_marker "QUALIFIER_PLATFORM_SABLE" "$QUALIFIER" \
  "N1B_PLATFORM_SABLE_DESIGN_TRACEABILITY"
require_marker "QUALIFIER_DEVICE_TRACEABILITY" "$QUALIFIER" \
  "N1B_DEVICE_SABLE_TITAN2_TRACEABILITY"
require_marker "QUALIFIER_OPEN_ISSUES" "$QUALIFIER" \
  "N1B_OPEN_ISSUE_TRACEABILITY"
require_marker "QUALIFIER_PASS_MARKER" "$QUALIFIER" \
  "N1B_PHYSICAL_UX_ACCEPTANCE_READINESS=PASS"

if [ "$FAILURES" -eq 0 ]; then
  say "N1B_PHYSICAL_UX_ACCEPTANCE_READINESS_CONTRACT=PASS"
  exit 0
fi

say "N1B_PHYSICAL_UX_ACCEPTANCE_READINESS_CONTRACT=FAIL"
say "FAILURES=$FAILURES"
exit 1
