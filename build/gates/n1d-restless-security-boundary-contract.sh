#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BOUNDARY="$ROOT/build/titan2/n1d-restless-security-boundary.env"
PRODUCT="$ROOT/build/titan2/n1d-product-contract.env"
TRANSITION="$ROOT/build/titan2/n1d-c3b-transition.env"
C3A_EVIDENCE="$ROOT/build/titan2/n1d-c3a-control-evidence.env"
HARDENER="$ROOT/build/titan2/apply-n1d-c3b-phh-base-hardening.py"
DOC="$ROOT/docs/titan2/N1D_RESTLESS_SECURITY_BOUNDARY_R1.md"

fail() {
    echo "N1D_RESTLESS_SECURITY_BOUNDARY_CONTRACT=FAIL $*" >&2
    exit 1
}

for f in "$BOUNDARY" "$PRODUCT" "$TRANSITION" "$C3A_EVIDENCE" "$HARDENER" "$DOC"; do
    [[ -f "$f" ]] || fail "missing_file=$f"
done
for f in "$BOUNDARY" "$PRODUCT" "$TRANSITION" "$C3A_EVIDENCE"; do
    bash -n "$f" || fail "syntax=$f"
done
python3 -m py_compile "$HARDENER" || fail "python_syntax=$HARDENER"

require_line() {
    local file="$1" line="$2"
    grep -Fxq "$line" "$file" || fail "missing_line=$line file=$file"
}

for required in     'N1D_RESTLESS_SECURITY_BOUNDARY_VERSION=5'     'N1D_RESTLESS_ROLE=C2_CONTROL_C3A_REPRODUCTION_REFERENCE_C3B_PATCH_SOURCE_ONLY'     'N1D_C2_CONTROL_MODE=PINNED_PREBUILT_RESTLESS_GSI'     'N1D_C2_CONTROL_TAG=16.0.0-202606230923'     'N1D_C2_CONTROL_COMMIT=4adc5766f457849ca37e0b318bced65aef5a2233'     'N1D_C3A_ROLE=RESTLESS_TREBLEDROID_REPRODUCTION_CONTROL'     'N1D_C3A_STATUS=SEALED_COMPLETE'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_PATCH_COUNT=369'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3_BUILD_TOPOLOGY=PINNED_GRAPHENE_PLUS_MINIMAL_TREBLEDROID_SCAFFOLD'     'N1D_C3_PHH_BUILD_SCAFFOLD_ALLOWED=YES_PINNED_ONLY'     'N1D_C3_DEVICE_PHH_TREBLE_COMMIT=39ba82ef89ff5bf6b22ca8f147dbf317bffa20ed'     'N1D_C3B_GRAPHENE_BASE_PROJECT_COUNT=1033'     'N1D_C3B_SCAFFOLD_PROJECT_COUNT=5'     'N1D_C3B_REMOVE_PROJECT_COUNT=0'     'N1D_C3B_MANAGED_PROJECT_COUNT=1038'     'N1D_C3B_PHH_BASE_SECURITY_TRANSFORM_COUNT=14'     'N1D_C3B_HOST_LAYOUT_PATCH_COUNT=2'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3_PRIVATE_RESTLESS_VENDOR_ALLOWED=NO'     'N1D_C3_PHH_BASE_RUNTIME_SECURITY_TRUST=NO'     'N1D_C3_PHH_INSECURE_DEFAULTS_REQUIRE_AUDIT=YES'     'N1D_C3_SELINUX_IGNORE_NEVERALLOWS_RELEASE_ALLOWED=NO'     'N1D_C3_RO_ADB_SECURE_ZERO_RELEASE_ALLOWED=NO'     'N1D_C3_PHH_REMOTE_DEBUG_RELEASE_ALLOWED=NO'     'N1D_C3_PHHSU_RELEASE_ALLOWED=NO'     'N1D_C3_VENDOR_MAGISK_RELEASE_ALLOWED=NO'     'N1D_C3_PHH_OTA_RELEASE_ALLOWED=NO'     'N1D_C3B_BUILD_AUTHORIZED=YES_SYSTEMIMAGE_ONLY_AFTER_STAGE_AND_PARSE'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_SIGNING_AUTHORIZED=NO'     'N1D_C3B_PHYSICAL_RUNTIME_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'     'N1D_C3_RELEASE_ELIGIBLE=NO'     'N1D_C3_RELEASE_REQUIRES_RUNTIME_SECURITY_CLOSURE=YES'     'N1D_RESTLESS_SECURITY_BOUNDARY=PASS'
do
    require_line "$BOUNDARY" "$required"
done

for required in     'N1D_PRODUCT_CONTRACT_VERSION=6'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_PRODUCT_GENERATOR_CONFIG=sable-c3b-engineering'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'     'N1D_C3_RELEASE_ELIGIBLE=NO'     'N1D_PRODUCT_CONTRACT=PASS'
do
    require_line "$PRODUCT" "$required"
done

for required in     'N1D_C3B_C3A_REQUIRED_SYSTEM_SHA256=4c292b9876a43f8df515a163a197e92d71deba598767790681f999ea3c554c16'     'N1D_C3_CURRENT_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3B_PHH_BASE_SECURITY_TRANSFORM_COUNT=14'     'N1D_C3B_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'
do
    require_line "$TRANSITION" "$required"
done

require_line "$C3A_EVIDENCE" 'N1D_C3A_CONTROL_EVIDENCE_STATUS=PASS_SYSTEMIMAGE'

for token in     'SELINUX_IGNORE_NEVERALLOWS := true'     'ro.adb.secure=0'     'persist.sys.usb.config=adb'     'phh-securize.sh'     'phh-remotectl'     'phh-ota'     'QcRilAm'     'MtkInCallService'
do
    grep -Fq "$token" "$HARDENER" || fail "hardening_target_missing=$token"
done

if grep -Fq 'N1D_C3_RELEASE_ELIGIBLE=YES' "$BOUNDARY" "$PRODUCT"; then
    fail premature_release_eligibility
fi
if grep -Fq 'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=YES' "$BOUNDARY" "$PRODUCT" "$TRANSITION"; then
    fail premature_device_contact
fi
if grep -Fq 'N1D_C3B_FLASH_AUTHORIZED=YES' "$BOUNDARY" "$PRODUCT" "$TRANSITION"; then
    fail premature_flash_authorization
fi

echo "N1D_RESTLESS_C2_CONTROL_SEPARATION=PASS"
echo "N1D_RESTLESS_C3A_CONTROL=PASS_SEALED"
echo "N1D_RESTLESS_C3B_PINNED_SCAFFOLD=PASS_MINIMAL count=5"
echo "N1D_RESTLESS_C3B_BASE_SECURITY_REDUCTION=PASS_EXACT count=14"
echo "N1D_RESTLESS_C3B_RESTLESS_PATCH_ADMISSION=PASS_ZERO"
echo "N1D_RESTLESS_C3B_RUNTIME_PATCH_ADMISSION=PASS_ZERO"
echo "N1D_RESTLESS_C3_PRIVATE_VENDOR=PASS_ABSENT"
echo "N1D_RESTLESS_C3_RELEASE_SECURITY_CLOSURE=PASS_REQUIRED"
echo "N1D_RESTLESS_SECURITY_BOUNDARY_CONTRACT=PASS"
