#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BOUNDARY="$ROOT/build/titan2/n1d-restless-security-boundary.env"
PRODUCT="$ROOT/build/titan2/n1d-product-contract.env"
PROFILE="$ROOT/build/titan2/n1d-c3-trebledroid.env"
DOC="$ROOT/docs/titan2/N1D_RESTLESS_SECURITY_BOUNDARY_R1.md"

fail() {
    echo "N1D_RESTLESS_SECURITY_BOUNDARY_CONTRACT=FAIL $*" >&2
    exit 1
}

for f in "$BOUNDARY" "$PRODUCT" "$PROFILE" "$DOC"; do
    [[ -f "$f" ]] || fail "missing_file=$f"
done
for f in "$BOUNDARY" "$PRODUCT" "$PROFILE"; do
    bash -n "$f" || fail "syntax=$f"
done

require_line() {
    local file="$1" line="$2"
    grep -Fxq "$line" "$file" || fail "missing_line=$line file=$file"
}

for required in     'N1D_RESTLESS_SECURITY_BOUNDARY_VERSION=4'     'N1D_RESTLESS_ROLE=C2_CONTROL_C3A_REPRODUCTION_REFERENCE_C3B_PATCH_SOURCE_ONLY'     'N1D_C2_CONTROL_MODE=PINNED_PREBUILT_RESTLESS_GSI'     'N1D_C2_CONTROL_TAG=16.0.0-202606230923'     'N1D_C2_CONTROL_COMMIT=4adc5766f457849ca37e0b318bced65aef5a2233'     'N1D_C3_BUILD_TOPOLOGY=PINNED_TREBLEDROID_GENERATED_PRODUCT'     'N1D_C3_PHH_BUILD_SCAFFOLD_ALLOWED=YES_PINNED_ONLY'     'N1D_C3_DEVICE_PHH_TREBLE_COMMIT=39ba82ef89ff5bf6b22ca8f147dbf317bffa20ed'     'N1D_C3_CONTROL_FULL_RESTLESS_PATCH_TIERS=YES_PINNED_CONTROL_ONLY'     'N1D_C3_CONTROL_PATCH_COUNT=369'     'N1D_C3_RESTLESS_FULL_PATCH_TIERS_AUTOAPPLY_ALLOWED_FOR_RELEASE=NO'     'N1D_C3_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3_PRIVATE_RESTLESS_VENDOR_ALLOWED=NO'     'N1D_C3_PHH_BASE_RUNTIME_SECURITY_TRUST=NO'     'N1D_C3_PHH_INSECURE_DEFAULTS_REQUIRE_AUDIT=YES'     'N1D_C3_SELINUX_IGNORE_NEVERALLOWS_RELEASE_ALLOWED=NO'     'N1D_C3_RO_ADB_SECURE_ZERO_RELEASE_ALLOWED=NO'     'N1D_C3_PHH_REMOTE_DEBUG_RELEASE_ALLOWED=NO'     'N1D_C3_PHHSU_RELEASE_ALLOWED=NO'     'N1D_C3_VENDOR_MAGISK_RELEASE_ALLOWED=NO'     'N1D_C3_PHH_OTA_RELEASE_ALLOWED=NO'     'N1D_C3_RELEASE_ELIGIBLE=NO'     'N1D_C3_RELEASE_REQUIRES_RUNTIME_SECURITY_CLOSURE=YES'     'N1D_C3A_ROLE=RESTLESS_TREBLEDROID_REPRODUCTION_CONTROL'     'N1D_C3A_ADD_PROJECT_COUNT=12'     'N1D_C3A_REMOVE_PROJECT_COUNT=54'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_FIDELITY=PUBLIC_FUNCTIONAL_REPRODUCTION'     'N1D_C3A_PRIVATE_RESTLESS_VENDOR=OMITTED'     'N1D_C3A_PIXEL_GSANS=OMITTED_UNPINNED_NONFUNCTIONAL'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3B_ROLE=SABLE_MINIMAL_BASELINE'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_AOSP_PHONE_STACK=SOURCE_BUILT'     'N1D_C3B_STOCK_TELEPHONY_APK_IMPORT_ALLOWED=NO'     'N1D_C3B_RADIO_COMPAT_MODE=EVIDENCE_DRIVEN'     'N1D_RESTLESS_SECURITY_BOUNDARY=PASS'
do
    require_line "$BOUNDARY" "$required"
done

for required in     'N1D_PRODUCT_CONTRACT_VERSION=5'     'N1D_PRODUCT_NAME=treble_arm64_bvN'     'N1D_PRODUCT_GENERATOR=device/phh/treble/generate.sh'     'N1D_DEVICE_PHH_TREBLE_GENERATOR_USED=YES_PINNED'     'N1D_DEVICE_PHH_TREBLE_BASE_PRESENT=YES_COMPATIBILITY_SUBSTRATE'     'N1D_CONTROL_FULL_RESTLESS_PATCH_TIERS=YES_PINNED_CONTROL_ONLY'     'N1D_RESTLESS_FULL_PATCH_TIERS_AUTOAPPLY_ALLOWED_FOR_RELEASE=NO'     'N1D_CONTROL_PATCH_COUNT=369'     'N1D_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3_RELEASE_ELIGIBLE=NO'     'N1D_C3_RUNTIME_SECURITY_AUDIT_REQUIRED=YES'     'N1D_PRODUCT_CONTRACT=PASS'
do
    require_line "$PRODUCT" "$required"
done

for required in     'N1D_C3_CONTROL_PATCH_COUNT=369'     'N1D_C3_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3_PRIVATE_VENDOR_ALLOWED=NO'     'N1D_C3_RELEASE_ELIGIBLE_BY_REBASELINE=NO'
do
    require_line "$PROFILE" "$required"
done

if grep -Fq 'N1D_C3_RELEASE_ELIGIBLE=YES' "$BOUNDARY" "$PRODUCT"; then
    fail premature_release_eligibility
fi

echo "N1D_RESTLESS_C2_CONTROL_SEPARATION=PASS"
echo "N1D_RESTLESS_C3A_PUBLIC_FUNCTIONAL_GRAPH=PASS managed=991"
echo "N1D_RESTLESS_C3_PINNED_PHH_SCAFFOLD=PASS"
echo "N1D_RESTLESS_C3_CONTROL_PATCH_STACK=PASS_PINNED_369"
echo "N1D_RESTLESS_C3_RELEASE_RUNTIME_ADMISSION=PASS_ZERO"
echo "N1D_RESTLESS_C3_PRIVATE_VENDOR=PASS_ABSENT"
echo "N1D_RESTLESS_C3_RELEASE_SECURITY_CLOSURE=PASS_REQUIRED"
echo "N1D_RESTLESS_SECURITY_BOUNDARY_CONTRACT=PASS"
