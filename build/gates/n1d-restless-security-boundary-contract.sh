do
    require_line "$BOUNDARY" "$required"
done

for required in     'N1D_PRODUCT_CONTRACT_VERSION=6'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_PRODUCT_NAME=treble_arm64_bvN'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3B_RELEASE_ELIGIBLE=NO'     'N1D_C3_RELEASE_ELIGIBLE=NO'     'N1D_PRODUCT_CONTRACT=PASS'
do
    require_line "$PRODUCT" "$required"
done

for required in     'N1D_C3_CONTROL_PATCH_COUNT=369'     'N1D_C3_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3_PRIVATE_VENDOR_ALLOWED=NO'     'N1D_C3_RELEASE_ELIGIBLE_BY_REBASELINE=NO'
do
    require_line "$C3A_PROFILE" "$required"
done

for required in     'N1D_C3_CURRENT_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3B_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'
do
    require_line "$TRANSITION" "$required"
done

for forbidden in     'N1D_C3_RELEASE_ELIGIBLE=YES'     'N1D_C3B_RELEASE_ELIGIBLE=YES'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=YES'     'N1D_C3B_FLASH_AUTHORIZED=YES'     'N1D_C3B_SIGNING_AUTHORIZED=YES'
do
    if grep -Fq "$forbidden" "$BOUNDARY" "$PRODUCT" "$TRANSITION"; then
        fail "forbidden_security_state=$forbidden"
    fi
done

echo "N1D_RESTLESS_C2_CONTROL_SEPARATION=PASS"
echo "N1D_RESTLESS_C3A_PUBLIC_FUNCTIONAL_GRAPH=PASS_SEALED managed=991"
echo "N1D_RESTLESS_C3B_MINIMAL_GRAPH=PASS managed=1038"
echo "N1D_RESTLESS_C3_CONTROL_PATCH_STACK=PASS_HISTORICAL_369"
echo "N1D_RESTLESS_C3B_RUNTIME_ADMISSION=PASS_ZERO"
echo "N1D_RESTLESS_C3_PRIVATE_VENDOR=PASS_ABSENT"
echo "N1D_RESTLESS_C3B_DEVICE_RELEASE_BOUNDARY=PASS_BLOCKED"
echo "N1D_RESTLESS_C3_RELEASE_SECURITY_CLOSURE=PASS_REQUIRED"
echo "N1D_RESTLESS_SECURITY_BOUNDARY_CONTRACT=PASS"
