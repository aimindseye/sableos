#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BOUNDARY="$ROOT/build/titan2/n1d-restless-security-boundary.env"
PRODUCT="$ROOT/build/titan2/n1d-product-contract.env"
C3A_PROFILE="$ROOT/build/titan2/n1d-c3-trebledroid.env"
TRANSITION="$ROOT/build/titan2/n1d-c3b-transition.env"
DOC="$ROOT/docs/titan2/N1D_RESTLESS_SECURITY_BOUNDARY_R1.md"

fail() {
    echo "N1D_RESTLESS_SECURITY_BOUNDARY_CONTRACT=FAIL $*" >&2
    exit 1
}

for f in "$BOUNDARY" "$PRODUCT" "$C3A_PROFILE" "$TRANSITION" "$DOC"; do
    [[ -f "$f" ]] || fail "missing_file=$f"
done
for f in "$BOUNDARY" "$PRODUCT" "$C3A_PROFILE" "$TRANSITION"; do
    bash -n "$f" || fail "syntax=$f"
done

require_line() {
    local file="$1" line="$2"
    grep -Fxq "$line" "$file" || fail "missing_line=$line file=$file"
}

for required in     'N1D_RESTLESS_SECURITY_BOUNDARY_VERSION=5'     'N1D_RESTLESS_ROLE=C2_CONTROL_C3A_REPRODUCTION_REFERENCE_C3B_PATCH_SOURCE_ONLY'     'N1D_C2_CONTROL_MODE=PINNED_PREBUILT_RESTLESS_GSI'     'N1D_C2_CONTROL_TAG=16.0.0-202606230923'     'N1D_C2_CONTROL_COMMIT=4adc5766f457849ca37e0b318bced65aef5a2233'     'N1D_C3A_ROLE=RESTLESS_TREBLEDROID_REPRODUCTION_CONTROL'     'N1D_C3A_STATUS=SEALED_COMPLETE'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_PATCH_COUNT=369'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3_BUILD_TOPOLOGY=PINNED_GRAPHENE_PLUS_MINIMAL_TREBLEDROID_SCAFFOLD'     'N1D_C3_PHH_BUILD_SCAFFOLD_ALLOWED=YES_PINNED_ONLY'     'N1D_C3_DEVICE_PHH_TREBLE_COMMIT=39ba82ef89ff5bf6b22ca8f147dbf317bffa20ed'     'N1D_C3B_GRAPHENE_BASE_PROJECT_COUNT=1033'     'N1D_C3B_SCAFFOLD_PROJECT_COUNT=5'     'N1D_C3B_REMOVE_PROJECT_COUNT=0'     'N1D_C3B_MANAGED_PROJECT_COUNT=1038'     'N1D_C3B_PHH_BASE_SECURITY_TRANSFORM_COUNT=14'     'N1D_C3B_HOST_LAYOUT_PATCH_COUNT=2'     'N1D_C3B_ROLE=SABLE_MINIMAL_ENGINEERING_BASELINE'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3B_AOSP_PHONE_STACK=SOURCE_BUILT'     'N1D_C3B_STOCK_TELEPHONY_APK_IMPORT_ALLOWED=NO'     'N1D_C3B_STOCK_MTK_JAR_SO_IMPORT_ALLOWED=NO'     'N1D_C3B_FULL_VENDOR_COPY_ALLOWED=NO'     'N1D_C3B_RADIO_COMPAT_MODE=EVIDENCE_DRIVEN'     'N1D_C3B_BUILD_AUTHORIZED=YES_SYSTEMIMAGE_ONLY_AFTER_STAGE_AND_PARSE'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_SIGNING_AUTHORIZED=NO'     'N1D_C3B_PHYSICAL_RUNTIME_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'     'N1D_C3_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3_PRIVATE_RESTLESS_VENDOR_ALLOWED=NO'     'N1D_C3_PHH_BASE_RUNTIME_SECURITY_TRUST=NO'     'N1D_C3_PHH_INSECURE_DEFAULTS_REQUIRE_AUDIT=YES'     'N1D_C3_SELINUX_IGNORE_NEVERALLOWS_RELEASE_ALLOWED=NO'     'N1D_C3_RO_ADB_SECURE_ZERO_RELEASE_ALLOWED=NO'     'N1D_C3_PHH_R