#!/usr/bin/env bash

ROOT="${1:-.}"
FAILURES=0

say() {
  printf '%s\n' "$1"
}

pass() {
  say "$1=PASS"
}

fail() {
  say "$1=FAIL"
  FAILURES=$((FAILURES + 1))
}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$ROOT/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_PATH=$PATH_VALUE"
  fi
}

require_marker() {
  NAME="$1"
  PATH_VALUE="$2"
  MARKER="$3"
  if grep -Fq "$MARKER" "$ROOT/$PATH_VALUE" 2>/dev/null; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_MARKER=$MARKER"
    say "IN_FILE=$PATH_VALUE"
  fi
}

say "===== N1B SETUP WIZARD KEYBOARD CHECK CONTRACT ====="
say "ROOT=$ROOT"
say "DOCUMENTATION_ONLY=YES"
say "BUILD_CODE_CHANGED=NO"
say "DEVICE_CODE_CHANGED=NO"
say "IMAGE_BUILD_AUTHORIZED=NO"
say "DEVICE_CONTACT_AUTHORIZED=NO"
say "FLASH_AUTHORIZED=NO"
say "ADB_COMMANDS_RUN=NO"
say "FASTBOOT_COMMANDS_RUN=NO"

CONTRACT="docs/titan2/N1B_SETUP_WIZARD_KEYBOARD_CHECK_CONTRACT.md"
OWNER="docs/titan2/N1B_SETUP_WIZARD_MODULE_OWNERSHIP.md"
SELF="build/gates/n1b-setup-wizard-keyboard-check-contract.sh"

require_file "N1B_SETUP_WIZARD_CONTRACT_FILE" "$CONTRACT"
require_file "N1B_SETUP_WIZARD_OWNER_FILE" "$OWNER"
require_file "N1B_SETUP_WIZARD_GATE_SCRIPT" "$SELF"

require_marker "N1B_SETUP_WIZARD_CONTRACT_MARKER" "$CONTRACT" \
  "N1B_SETUP_WIZARD_KEYBOARD_CHECK_CONTRACT=YES"
require_marker "N1B_SETUP_WIZARD_CODE_OWNER_ABSENT_RECORDED" "$CONTRACT" \
  "N1B_SETUP_WIZARD_CODE_OWNER_CURRENTLY_FOUND=NO"
require_marker "N1B_SETUP_WIZARD_IMPLEMENTATION_REQUIRED" "$CONTRACT" \
  "N1B_SETUP_WIZARD_IMPLEMENTATION_REQUIRED=YES"
require_marker "N1B_SETUP_WIZARD_IMAGE_BLOCKER" "$CONTRACT" \
  "N1B_SETUP_WIZARD_IMAGE_BLOCKER=YES"
require_marker "PHYSICAL_KEYBOARD_VERIFICATION_REQUIRED" "$CONTRACT" \
  "PHYSICAL_KEYBOARD_VERIFICATION_SCREEN=YES"
require_marker "SOFTWARE_KEYBOARD_FALLBACK_REQUIRED" "$CONTRACT" \
  "SOFTWARE_KEYBOARD_FALLBACK_AVAILABLE=YES"
require_marker "CRITICAL_TEXT_ENTRY_REQUIRED" "$CONTRACT" \
  "CRITICAL_TEXT_ENTRY_TEST=YES"
require_marker "PANTHER_PROFILE_PROTECTION" "$CONTRACT" \
  "PANTHER_TOUCH_FIRST_REFERENCE_PROTECTED=YES"
require_marker "IMAGE_BUILD_BLOCKED" "$CONTRACT" \
  "IMAGE_BUILD_BLOCKED_UNTIL_CODE_PHYSICAL_CI_PASS=YES"

require_marker "MODULE_OWNERSHIP_MARKER" "$OWNER" \
  "N1B_SETUP_WIZARD_MODULE_OWNERSHIP=YES"
require_marker "OWNER_REQUIRED_MARKER" "$OWNER" \
  "SETUP_WIZARD_OWNER_REQUIRED=YES"
require_marker "IMPLEMENTATION_ABSENT_MARKER" "$OWNER" \
  "SETUP_WIZARD_IMPLEMENTATION_ABSENT=YES"
require_marker "NEXT_PR_OWNER_MARKER" "$OWNER" \
  "SETUP_WIZARD_NEXT_PR_MUST_ADD_OR_BIND_OWNER=YES"
require_marker "EXACT_BUILD_COMMAND_REQUIRED" "$OWNER" \
  "SETUP_WIZARD_EXACT_BUILD_COMMAND_REQUIRED=YES"
require_marker "STAGE_B_REQUIRED_MARKER" "$OWNER" \
  "STAGE_B_PHYSICAL_UX_REQUIRED=YES"

if [ "$FAILURES" -eq 0 ]; then
  say "N1B_SETUP_WIZARD_KEYBOARD_CHECK_CONTRACT=PASS"
  exit 0
fi

say "N1B_SETUP_WIZARD_KEYBOARD_CHECK_CONTRACT=FAIL"
say "FAILURES=$FAILURES"
exit 1
