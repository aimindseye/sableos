#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SPLIT="$ROOT/build/titan2/n1d-c3-phase-split.env"
PRODUCT="$ROOT/build/titan2/n1d-product-contract.env"
BOUNDARY="$ROOT/build/titan2/n1d-restless-security-boundary.env"
COMPOSITION="$ROOT/build/titan2/n1d-c3-composition.env"

fail() {
    echo "N1D_C3_PHASE_SPLIT_CONTRACT=FAIL $*" >&2
    exit 1
}

for f in "$SPLIT" "$PRODUCT" "$BOUNDARY" "$COMPOSITION"; do
    [[ -f "$f" ]] || fail "missing_file=$f"
done
bash -n "$SPLIT" "$PRODUCT" "$BOUNDARY" "$COMPOSITION"

require_line() {
    local file="$1" line="$2"
    grep -Fxq "$line" "$file" || fail "missing_line=$line file=$file"
}

for required in     'N1D_C3_PHASE_SPLIT_VERSION=2'     'N1D_C3A_ROLE=RESTLESS_TREBLEDROID_REPRODUCTION_CONTROL'     'N1D_C3A_PRODUCT=treble_arm64_bvN'     'N1D_C3A_ADD_PROJECT_COUNT=12'     'N1D_C3A_REMOVE_PROJECT_COUNT=54'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_FIDELITY=PUBLIC_FUNCTIONAL_REPRODUCTION'     'N1D_C3A_ADD_PROJECT_COUNT=12'     'N1D_C3A_REMOVE_PROJECT_COUNT=54'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_FIDELITY=PUBLIC_FUNCTIONAL_REPRODUCTION'     'N1D_C3A_CONTROL_PATCH_COUNT=369'     'N1D_C3A_FULL_RESTLESS_PATCH_STACK_ALLOWED=YES_CONTROL_ONLY'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3A_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3A_FLASH_AUTHORIZED=NO'     'N1D_C3B_ROLE=SABLE_MINIMAL_BASELINE'     'N1D_C3B_SOURCE_SUBSTRATE=GRAPHENEOS_A16_PINNED'     'N1D_C3B_TREBLEDROID_SCAFFOLD_ALLOWED=YES_PINNED_BUILD_COMPAT_ONLY'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_RUNTIME_PATCH_ALLOWLIST_INITIAL_COUNT=0'     'N1D_C3B_PATCH_ADMISSION_MODE=FAILURE_EVIDENCE_THEN_REVIEW_THEN_ADMIT'     'N1D_C3B_AOSP_PHONE_STACK=SOURCE_BUILT'     'N1D_C3B_STOCK_TELEPHONY_APK_IMPORT_ALLOWED=NO'     'N1D_C3B_STOCK_MTK_JAR_SO_IMPORT_ALLOWED=NO'     'N1D_C3B_FULL_VENDOR_COPY_ALLOWED=NO'     'N1D_C3B_STOCK_VENDOR_FIRMWARE_PRESERVE=YES'     'N1D_C3B_RADIO_COMPAT_MODE=EVIDENCE_DRIVEN'     'N1D_C3B_MTK_INDICATION_STATUS=INVESTIGATE'     'N1D_C3B_IMS_QNS_IWLAN_STATUS=INVESTIGATE'     'N1D_C3B_PHH_MTK_IMS_DEFAULT=false'     'N1D_C3B_APN_ONLY_FIX_ALLOWED=NO'     'N1D_C3B_LTE_ONLY_FIX_ALLOWED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'     'N1D_C3B_BUILD_AUTHORIZED=NO_UNTIL_C3A_CONTROL_EVIDENCE'     'N1D_C3_PHASE_SPLIT=PASS'
do
    require_line "$SPLIT" "$required"
done

for required in     'N1D_PRODUCT_CONTRACT_VERSION=5'     'N1D_C3_ACTIVE_PHASE=C3A_CONTROL'     'N1D_C3A_ROLE=RESTLESS_TREBLEDROID_REPRODUCTION_CONTROL'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3B_ROLE=SABLE_MINIMAL_BASELINE'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_BUILD_AUTHORIZED=NO_UNTIL_C3A_CONTROL_EVIDENCE'
do
    require_line "$PRODUCT" "$required"
done

for required in     'N1D_RESTLESS_SECURITY_BOUNDARY_VERSION=4'     'N1D_C3A_ROLE=RESTLESS_TREBLEDROID_REPRODUCTION_CONTROL'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3B_ROLE=SABLE_MINIMAL_BASELINE'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_AOSP_PHONE_STACK=SOURCE_BUILT'     'N1D_C3B_STOCK_TELEPHONY_APK_IMPORT_ALLOWED=NO'     'N1D_C3B_RADIO_COMPAT_MODE=EVIDENCE_DRIVEN'
do
    require_line "$BOUNDARY" "$required"
done

for required in     'N1D_C3_COMPOSITION_VERSION=4'     'N1D_C3_ACTIVE_PHASE=C3A_CONTROL'     'N1D_C3A_ADD_PROJECT_COUNT=12'     'N1D_C3A_REMOVE_PROJECT_COUNT=54'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_PATCH_COUNT=369'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_BUILD_AUTHORIZED=NO_UNTIL_C3A_CONTROL_EVIDENCE'
do
    require_line "$COMPOSITION" "$required"
done

if grep -Fq 'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=YES'     "$SPLIT" "$PRODUCT" "$BOUNDARY" "$COMPOSITION"; then
    fail c3b_full_restless_stack_enabled
fi
if grep -Fq 'N1D_C3B_BUILD_AUTHORIZED=YES'     "$SPLIT" "$PRODUCT" "$BOUNDARY" "$COMPOSITION"; then
    fail c3b_build_prematurely_authorized
fi

echo "N1D_C3A_CONTROL_BOUNDARY=PASS"
echo "N1D_C3B_MINIMAL_BASELINE_BOUNDARY=PASS"
echo "N1D_C3B_FULL_RESTLESS_STACK=PASS_BLOCKED"
echo "N1D_C3B_RADIO_POLICY=PASS_EVIDENCE_DRIVEN"
echo "N1D_C3_PHASE_SPLIT_CONTRACT=PASS"
