#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SPLIT="$ROOT/build/titan2/n1d-c3-phase-split.env"
PRODUCT="$ROOT/build/titan2/n1d-product-contract.env"
BOUNDARY="$ROOT/build/titan2/n1d-restless-security-boundary.env"
COMPOSITION="$ROOT/build/titan2/n1d-c3-composition.env"
TRANSITION="$ROOT/build/titan2/n1d-c3b-transition.env"

fail() {
    echo "N1D_C3_PHASE_SPLIT_CONTRACT=FAIL $*" >&2
    exit 1
}

for f in "$SPLIT" "$PRODUCT" "$BOUNDARY" "$COMPOSITION" "$TRANSITION"; do
    [[ -f "$f" ]] || fail "missing_file=$f"
    bash -n "$f" || fail "syntax=$f"
done

require_line() {
    local file="$1" line="$2"
    grep -Fxq "$line" "$file" || fail "missing_line=$line file=$file"
}

for required in     'N1D_C3_PHASE_SPLIT_VERSION=3'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3A_ROLE=RESTLESS_TREBLEDROID_REPRODUCTION_CONTROL'     'N1D_C3A_STATUS=SEALED_COMPLETE'     'N1D_C3A_PRODUCT=treble_arm64_bvN'     'N1D_C3A_ADD_PROJECT_COUNT=12'     'N1D_C3A_REMOVE_PROJECT_COUNT=54'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_FIDELITY=PUBLIC_FUNCTIONAL_REPRODUCTION'     'N1D_C3A_CONTROL_PATCH_COUNT=369'     'N1D_C3A_FULL_RESTLESS_PATCH_STACK_ALLOWED=YES_CONTROL_ONLY'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3A_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3A_FLASH_AUTHORIZED=NO'     'N1D_C3B_ROLE=SABLE_MINIMAL_ENGINEERING_BASELINE'     'N1D_C3B_SOURCE_SUBSTRATE=GRAPHENEOS_A16_PINNED'     'N1D_C3B_GRAPHENE_BASE_PROJECT_COUNT=1033'     'N1D_C3B_TREBLEDROID_SCAFFOLD_ALLOWED=YES_PINNED_BUILD_COMPAT_ONLY'     'N1D_C3B_SCAFFOLD_PROJECT_COUNT=5'     'N1D_C3B_REMOVE_PROJECT_COUNT=0'     'N1D_C3B_MANAGED_PROJECT_COUNT=1038'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3B_RUNTIME_PATCH_ALLOWLIST_INITIAL_COUNT=0'     'N1D_C3B_PATCH_ADMISSION_MODE=FAILURE_EVIDENCE_THEN_REVIEW_THEN_ADMIT'     'N1D_C3B_AOSP_PHONE_STACK=SOURCE_BUILT'     'N1D_C3B_STOCK_TELEPHONY_APK_IMPORT_ALLOWED=NO'     'N1D_C3B_STOCK_MTK_JAR_SO_IMPORT_ALLOWED=NO'     'N1D_C3B_FULL_VENDOR_COPY_ALLOWED=NO'     'N1D_C3B_STOCK_VENDOR_FIRMWARE_PRESERVE=YES'     'N1D_C3B_RADIO_COMPAT_MODE=EVIDENCE_DRIVEN'     'N1D_C3B_MTK_INDICATION_STATUS=INVESTIGATE'     'N1D_C3B_IMS_QNS_IWLAN_STATUS=INVESTIGATE'     'N1D_C3B_PHH_MTK_IMS_DEFAULT=false'     'N1D_C3B_APN_ONLY_FIX_ALLOWED=NO'     'N1D_C3B_LTE_ONLY_FIX_ALLOWED=NO'     'N1D_C3B_ENGINEERING_BUILD_AUTHORIZED=YES_SYSTEMIMAGE_ONLY_AFTER_STAGE_AND_PARSE'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_SIGNING_AUTHORIZED=NO'     'N1D_C3B_PHYSICAL_RUNTIME_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'     'N1D_C3_PHASE_SPLIT=PASS'
do
    require_line "$SPLIT" "$required"
done

for required in     'N1D_PRODUCT_CONTRACT_VERSION=6'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3A_STATUS=SEALED_COMPLETE'     'N1D_C3B_ROLE=SABLE_MINIMAL_ENGINEERING_BASELINE'     'N1D_C3B_GRAPHENE_BASE_PROJECT_COUNT=1033'     'N1D_C3B_SCAFFOLD_PROJECT_COUNT=5'     'N1D_C3B_REMOVE_PROJECT_COUNT=0'     'N1D_C3B_MANAGED_PROJECT_COUNT=1038'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3B_BUILD_AUTHORIZED=YES_SYSTEMIMAGE_ONLY_AFTER_STAGE_AND_PARSE'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_SIGNING_AUTHORIZED=NO'     'N1D_C3B_PHYSICAL_RUNTIME_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'
do
    require_line "$PRODUCT" "$required"
done

for required in     'N1D_RESTLESS_SECURITY_BOUNDARY_VERSION=5'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3A_STATUS=SEALED_COMPLETE'     'N1D_C3B_ROLE=SABLE_MINIMAL_ENGINEERING_BASELINE'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3B_FLASH_AUTHORIZED=NO'     'N1D_C3B_SIGNING_AUTHORIZED=NO'     'N1D_C3B_RELEASE_ELIGIBLE=NO'
do
    require_line "$BOUNDARY" "$required"
done

for required in     'N1D_C3_COMPOSITION_VERSION=5'     'N1D_C3_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3_COMPOSITION_MODE=PINNED_GRAPHENE_PLUS_MINIMAL_TREBLEDROID_SCAFFOLD'     'N1D_C3B_GRAPHENE_BASE_PROJECT_COUNT=1033'     'N1D_C3B_SCAFFOLD_PROJECT_COUNT=5'     'N1D_C3B_REMOVE_PROJECT_COUNT=0'     'N1D_C3B_MANAGED_PROJECT_COUNT=1038'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3B_RUNTIME_PATCH_ALLOWLIST_INITIAL_COUNT=0'     'N1D_C3B_BUILD_AUTHORIZED=YES_SYSTEMIMAGE_ONLY_AFTER_STAGE_AND_PARSE'     'N1D_C3B_RELEASE_ELIGIBLE=NO'     'N1D_C3_DEVICE_CONTACT_AUTHORIZED=NO'     'N1D_C3_FLASH_AUTHORIZED=NO'     'N1D_C3_SIGNING_AUTHORIZED=NO'
do
    require_line "$COMPOSITION" "$required"
done

for required in     'N1D_C3_CURRENT_ACTIVE_PHASE=C3B_ENGINEERING'     'N1D_C3B_C3A_REQUIRED_STATUS=PASS_SYSTEMIMAGE'     'N1D_C3B_RESTLESS_PATCH_COUNT=0'     'N1D_C3B_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3B_RELEASE_ELIGIBLE=NO'
do
    require_line "$TRANSITION" "$required"
done

if grep -Fq 'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=YES'     "$SPLIT" "$PRODUCT" "$BOUNDARY" "$COMPOSITION" "$TRANSITION"
then
    fail c3b_full_restless_stack_enabled
fi

for forbidden in     'N1D_C3B_DEVICE_CONTACT_AUTHORIZED=YES'     'N1D_C3B_FLASH_AUTHORIZED=YES'     'N1D_C3B_SIGNING_AUTHORIZED=YES'     'N1D_C3B_PHYSICAL_RUNTIME_AUTHORIZED=YES'     'N1D_C3B_RELEASE_ELIGIBLE=YES'
do
    if grep -Fq "$forbidden" "$SPLIT" "$PRODUCT" "$BOUNDARY" "$COMPOSITION" "$TRANSITION"; then
        fail "forbidden_c3b_state=$forbidden"
    fi
done

echo "N1D_C3A_CONTROL_BOUNDARY=PASS_SEALED"
echo "N1D_C3A_PUBLIC_FUNCTIONAL_GRAPH=PASS managed=991"
echo "N1D_C3B_ACTIVE_ENGINEERING_PHASE=PASS"
echo "N1D_C3B_MINIMAL_BASELINE_BOUNDARY=PASS"
echo "N1D_C3B_FULL_RESTLESS_STACK=PASS_BLOCKED"
echo "N1D_C3B_RUNTIME_PATCH_ADMISSION=PASS_ZERO"
echo "N1D_C3B_DEVICE_RELEASE_BOUNDARY=PASS_BLOCKED"
echo "N1D_C3B_RADIO_POLICY=PASS_EVIDENCE_DRIVEN"
echo "N1D_C3_PHASE_SPLIT_CONTRACT=PASS"
