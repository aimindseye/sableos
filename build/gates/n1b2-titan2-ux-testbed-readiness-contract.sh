#!/usr/bin/env bash
set -euo pipefail

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
DOC="$ROOT/docs/titan2/N1B2_TITAN2_UX_TESTBED_READINESS_MATRIX.md"

fail() {
  echo "N1B2_UX_TESTBED_READINESS_FAILURE=$*" >&2
  exit 1
}

require_file() {
  local path="$1"
  [[ -f "$path" ]] || fail "missing file: $path"
}

require_text() {
  local pattern="$1"
  local path="$2"
  grep -Fq "$pattern" "$path" || fail "missing required marker '$pattern' in $path"
}

value_for() {
  local key="$1"
  local line
  line="$(grep -E "^${key}=" "$DOC" | tail -n 1 || true)"
  [[ -n "$line" ]] || fail "missing matrix row: $key"
  printf '%s\n' "${line#*=}"
}

require_status() {
  local key="$1"
  local value
  value="$(value_for "$key")"
  case "$value" in
    PASS|POLICY_PRESENT|EXPLICIT_BOUNDED_DEFERRAL)
      printf 'N1B2_UX_ROW=%s STATUS=%s\n' "$key" "$value"
      ;;
    *)
      fail "invalid status for $key: $value"
      ;;
  esac
}

echo "===== N1B2 TITAN2 UX TESTBED READINESS CONTRACT ====="
echo "ROOT=$ROOT"
echo "DOC=$DOC"

require_file "$DOC"

require_text "N1B2_TITAN2_UX_TESTBED_READINESS_MATRIX=YES" "$DOC"
require_text "N1B2_UX_TESTBED_ALLOWED_STATUS_SET=PASS|POLICY_PRESENT|EXPLICIT_BOUNDED_DEFERRAL" "$DOC"
require_text "N1B2_UX_TESTBED_FAIL_ON_UNDECIDED_ROW=YES" "$DOC"
require_text "N1B2_UX_TESTBED_PACKAGING_GATE_REQUIRED=YES" "$DOC"
require_text "N1B2_UX_TESTBED_TARGET_FILES_MARKER_REQUIRED=YES" "$DOC"
require_text "N1B2_FLASH_ALLOWED=NO_SEPARATE_GATE_REQUIRED" "$DOC"
require_text "PUBLIC_RELEASE=NO" "$DOC"
require_text "PRODUCTION_SIGNING=NO" "$DOC"

required_rows=(
  UX_SETUP_WIZARD_FIRST_BOOT_PHYSICAL_KEYBOARD_CHECK
  UX_CRITICAL_TEXT_ENTRY_GATES
  UX_LOCKSCREEN_SECURE_ENTRY_PATH
  UX_SABLE_START_KEYBOARD_FIRST_UX
  UX_ALL_APPS_PRIVACY_SUMMARIES_FAVORITES_SORTING
  UX_SABLE_COMMAND_SEARCH
  UX_HUB_MESSAGES_MAIL_PEOPLE_FAVORITES
  UX_DUPLICATE_MESSAGES_CLEANUP
  UX_QUICK_SETTINGS_NOTIFICATION_SHADE_THEME_BRANDING_HANDOFF
  UX_GLOBAL_THEME_PROPAGATION
  UX_BROWSER_VANADIUM_LABEL_ACCURACY
  UX_CONTACTS_PHONE_ALPHABET_RAIL
  UX_READER_THEME_OR_VAACHAK_IMPORT
  UX_MEDIA_PORTRAIT_DENSITY
  UX_FIRST_PARTY_APP_ICON_IDENTITY_AUDIT
  UX_N1B_TRACEABILITY_PLATFORM_SABLE_DOCS
  UX_N1B_TRACEABILITY_OPEN_ISSUES
  UX_N1B_TRACEABILITY_DEVICE_SABLE_TITAN2_GATES
  UX_R7E_ANDROID16_RESTLESS_INTERNAL_SUBSTRATE
  UX_N0B_KNOWN_DEVIATIONS_RECORDED
  UX_NO_PUBLIC_RELEASE_NO_FLASH_NO_PRODUCTION_SIGNING
  POLICY_SABLE_KEYBOARD_IME_BOUNDARY
  POLICY_KF1_KF2_KEYBOARD_CONTRACTS
  POLICY_TITAN2_SIDEKEY_TOUCHSURFACE_KEYBOARD_BACKLIGHT_DEFAULTS
  POLICY_DEVELOPER_WORK_PROFILE_TOOLS
  POLICY_SABLE_TOOLS_READ_ONLY_DIAGNOSTICS
  POLICY_APP_DISPLAY_COMPATIBILITY_PROFILES
  POLICY_PRIVATE_SPACE_WORK_PROFILE_APP_LOCK_BOUNDARIES
  POLICY_NETWORK_MANAGER_AUTHORITY_NO_DUPLICATE_NETWORK_BLOCKER
  POLICY_SUBSCREEN_SHORTCUT_KEYBOARD_GESTURE
  POLICY_CAMERA_CAMERA2_FIRST
  POLICY_FM_RADIO_IR_HARDWARE_UTILITIES_GATED
)

for row in "${required_rows[@]}"; do
  require_status "$row"
done

# Explicitly rejected unresolved statuses anywhere in the matrix document.
for forbidden in '=TODO' '=UNKNOWN' '=PENDING' '=FAIL' '=NO' '=BLOCKED' '=TBD' '=UNDECIDED' '=MISSING'; do
  if grep -Fq "$forbidden" "$DOC"; then
    fail "forbidden unresolved marker present: $forbidden"
  fi
done

require_text "CONTACTS_PHONE_ALPHABET_RAIL_DEFERRAL_BOUND=" "$DOC"
require_text "READER_THEME_VAACHAK_DEFERRAL_BOUND=" "$DOC"
require_text "MEDIA_PORTRAIT_DENSITY_DEFERRAL_BOUND=" "$DOC"

require_text "N1B2_UX_TESTBED_MATRIX_GATE=PASS" "$DOC"
require_text "N1B2_PRODUCT_PROFILE_GATE=PASS" "$DOC"
require_text "N1B2_SETUP_WIZARD_GATE=PASS" "$DOC"
require_text "N1B2_SABLE_HOME_GATE=PASS" "$DOC"
require_text "N1B2_TARGET_FILES_PRODUCT_CLOSURE_MARKER=PASS" "$DOC"
require_text "N1B2_TARGET_FILES_UX_TESTBED_MARKER=PASS" "$DOC"
require_text "N1B2_ARTIFACT_REGISTRATION_BLOCKS_ON_MATRIX=YES" "$DOC"
require_text "SYSTEM/etc/sableos/n1b2/ux-testbed-readiness.env" "$DOC"

require_text "FLASH_AUTHORIZED_BY_THIS_MATRIX=NO" "$DOC"
require_text "FACTORY_RESET_AUTHORIZED_BY_THIS_MATRIX=NO" "$DOC"
require_text "PUBLIC_RELEASE_AUTHORIZED_BY_THIS_MATRIX=NO" "$DOC"
require_text "PRODUCTION_SIGNING_AUTHORIZED_BY_THIS_MATRIX=NO" "$DOC"
require_text "STOCK_VENDOR_REPACK_AUTHORIZED_BY_THIS_MATRIX=NO" "$DOC"

echo "N1B2_UX_TESTBED_ROWS=${#required_rows[@]}"
echo "N1B2_UX_TESTBED_READINESS_MATRIX=PASS"
echo "N1B2_UX_TESTBED_ALLOWED_STATUS_SET=PASS_POLICY_PRESENT_EXPLICIT_BOUNDED_DEFERRAL"
echo "N1B2_UX_TESTBED_PACKAGING_GATE=PASS"
echo "N1B2_FLASH_ALLOWED=NO_SEPARATE_GATE_REQUIRED"
echo "N1B2_TITAN2_UX_TESTBED_READINESS_CONTRACT=PASS"
