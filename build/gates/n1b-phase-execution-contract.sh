#!/usr/bin/env bash

ROOT="${1:-.}"
FAILURES=0

say() {
  printf '%s\n' "$1"
}

pass() {
  say "$1=PASS"
}

fail() {
  say "$1=FAIL"
  FAILURES=$((FAILURES + 1))
}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$ROOT/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_PATH=$PATH_VALUE"
  fi
}

require_marker() {
  NAME="$1"
  PATH_VALUE="$2"
  MARKER="$3"
  if grep -Fq "$MARKER" "$ROOT/$PATH_VALUE" 2>/dev/null; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_MARKER=$MARKER"
    say "IN_FILE=$PATH_VALUE"
  fi
}

say "===== N1B PHASE EXECUTION CONTRACT ====="
say "ROOT=$ROOT"
say "SOURCE_MUTATION_AUTHORIZED=NO"
say "BUILD_AUTHORIZED=NO"
say "IMAGE_BUILD_AUTHORIZED=NO"
say "DEVICE_CONTACT_AUTHORIZED=NO"
say "FLASH_AUTHORIZED=NO"
say "ADB_COMMANDS_RUN=NO"
say "FASTBOOT_COMMANDS_RUN=NO"
say "PUBLIC_RELEASE=NO"

LEDGER="docs/titan2/N1B_PHASE_EXECUTION_LEDGER.md"
QUALIFIER="build/titan2/qualify-n1b-phase-execution.sh"
SELF="build/gates/n1b-phase-execution-contract.sh"

require_file "N1B_PHASE_EXECUTION_LEDGER_DOC" "$LEDGER"
require_file "N1B_PHASE_EXECUTION_QUALIFIER" "$QUALIFIER"
require_file "N1B_PHASE_EXECUTION_CONTRACT" "$SELF"

require_marker "LEDGER_MARKER" "$LEDGER" \
  "N1B_PHASE_EXECUTION_LEDGER=YES"
require_marker "LEDGER_STACKED_MARKER" "$LEDGER" \
  "N1B_STACKED_PRS_REQUIRED=YES"
require_marker "LEDGER_PHASE_01_MARKER" "$LEDGER" \
  "N1B_PHASE_01=FAST_LANE_SDK_PREFLIGHT"
require_marker "LEDGER_PHASE_03_MARKER" "$LEDGER" \
  "N1B_PHASE_03=SABLE_IDENTITY_AND_APP_COMPOSITION_STATIC_GATES"
require_marker "LEDGER_PHASE_08_MARKER" "$LEDGER" \
  "N1B_PHASE_08=N1B_IMAGE_BUILD_CANDIDATE"
require_marker "LEDGER_FLASH_BOUNDARY_MARKER" "$LEDGER" \
  "N1B_FLASH_REQUIRES_RESTORE_REPORT=YES"
require_marker "QUALIFIER_NO_BUILD" "$QUALIFIER" \
  "BUILD_AUTHORIZED=NO"
require_marker "QUALIFIER_NO_DEVICE" "$QUALIFIER" \
  "DEVICE_CONTACT_AUTHORIZED=NO"
require_marker "QUALIFIER_PASS_MARKER" "$QUALIFIER" \
  "N1B_PHASE_EXECUTION=PASS"

if [ "$FAILURES" -eq 0 ]; then
  say "N1B_PHASE_EXECUTION_CONTRACT=PASS"
  exit 0
fi

say "N1B_PHASE_EXECUTION_CONTRACT=FAIL"
say "FAILURES=$FAILURES"
exit 1
