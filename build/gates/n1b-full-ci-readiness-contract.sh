ROOT="${1:-.}"
FAILURES=0

say() {
  printf '%s\n' "$1"
}

pass() {
  say "$1=PASS"
}

fail() {
  say "$1=FAIL"
  FAILURES=$((FAILURES + 1))
}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$ROOT/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_PATH=$PATH_VALUE"
  fi
}

require_marker() {
  NAME="$1"
  PATH_VALUE="$2"
  MARKER="$3"
  if grep -Fq "$MARKER" "$ROOT/$PATH_VALUE" 2>/dev/null; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_MARKER=$MARKER"
    say "IN_FILE=$PATH_VALUE"
  fi
}

