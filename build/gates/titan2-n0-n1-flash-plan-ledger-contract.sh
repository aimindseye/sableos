#!/usr/bin/env bash

ROOT="${1:-.}"
FAILURES=0

say() {
  printf '%s\n' "$1"
}

pass() {
  say "$1=PASS"
}

fail() {
  say "$1=FAIL"
  FAILURES=$((FAILURES + 1))
}

require_file() {
  NAME="$1"
  PATH_VALUE="$2"
  if [ -f "$ROOT/$PATH_VALUE" ]; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_PATH=$PATH_VALUE"
  fi
}

require_marker() {
  NAME="$1"
  PATH_VALUE="$2"
  MARKER="$3"
  if grep -Fq "$MARKER" "$ROOT/$PATH_VALUE" 2>/dev/null; then
    pass "$NAME"
  else
    fail "$NAME"
    say "MISSING_MARKER=$MARKER"
    say "IN_FILE=$PATH_VALUE"
  fi
}

say "===== TITAN2 N0/N1 FLASH PLAN LEDGER CONTRACT ====="
say "ROOT=$ROOT"
say "SOURCE_MUTATION_AUTHORIZED=NO"
say "IMAGE_BUILD_AUTHORIZED=NO"
say "DEVICE_CONTACT_AUTHORIZED=NO"
say "FLASH_AUTHORIZED=NO"
say "ADB_COMMANDS_RUN=NO"
say "FASTBOOT_COMMANDS_RUN=NO"
say "PUBLIC_RELEASE=NO"

LEDGER="docs/titan2/N0_N1_FLASH_PLAN_LEDGER.md"
SELF="build/gates/titan2-n0-n1-flash-plan-ledger-contract.sh"

require_file "TITAN2_N0_N1_FLASH_LEDGER_FILE" "$LEDGER"
require_file "TITAN2_N0_N1_FLASH_LEDGER_GATE" "$SELF"

require_marker "LEDGER_MARKER" "$LEDGER" "TITAN2_N0_N1_FLASH_PLAN_LEDGER=YES"
require_marker "TREBLE_PORTABILITY_LANE" "$LEDGER" "LANE=TREBLE_PORTABILITY"
require_marker "NO_PIXEL_FASTBOOT_ASSUMPTIONS" "$LEDGER" "PIXEL_FASTBOOT_ASSUMPTIONS_ALLOWED=NO"
require_marker "NO_PANTHER_ARTIFACT_FLASH" "$LEDGER" "PANTHER_ARTIFACT_FLASH_TO_TITAN2_ALLOWED=NO"
require_marker "NO_WRITE_SCRIPT_UNTIL_REVIEW" "$LEDGER" "FLASH_SCRIPT_CREATED=NO_UNTIL_REVIEWED"
require_marker "FASTBOOT_BOOT_UNSUPPORTED" "$LEDGER" "FASTBOOT_BOOT=UNSUPPORTED"
require_marker "DSU_UNAVAILABLE" "$LEDGER" "DSU=UNAVAILABLE_ON_TESTED_STOCK_BUILD"
require_marker "FASTBOOTD_VERIFY_REQUIRED" "$LEDGER" "FASTBOOTD_MUST_BE_VERIFIED_BY_GETVAR_IS_USERSPACE_YES=YES"
require_marker "VIRTUAL_AB_RECORDED" "$LEDGER" "VIRTUAL_AB=true"
require_marker "RECOVERY_PATH_RECORDED" "$LEDGER" "RECOVERY_PATH=vendor_boot_recovery_vendor_ramdisk"
require_marker "RESTORE_REPORT_REQUIRED" "$LEDGER" "RESTORE_REPORT=REQUIRED"
require_marker "BOOTLOADER_PREFLIGHT_REQUIRED" "$LEDGER" "BOOTLOADER_PREFLIGHT=REQUIRED"
require_marker "FASTBOOTD_PREFLIGHT_REQUIRED" "$LEDGER" "FASTBOOTD_PREFLIGHT=REQUIRED"
require_marker "SNAPSHOT_NONE_REQUIRED" "$LEDGER" "SNAPSHOT_UPDATE_STATUS=none"
require_marker "ARTIFACT_SHA_REQUIRED" "$LEDGER" "ARTIFACT_SHA256=REQUIRED"
require_marker "ARTIFACT_LOGICAL_BYTES_REQUIRED" "$LEDGER" "ARTIFACT_LOGICAL_BYTES=REQUIRED"
require_marker "USERDATA_POLICY_REQUIRED" "$LEDGER" "USERDATA_POLICY=preserve|explicit-wipe-approved"
require_marker "EXPLICIT_SERIAL_REQUIRED" "$LEDGER" "EXPLICIT_TITAN_SERIAL=REQUIRED"
require_marker "IMPLICIT_WIPE_BLOCKED" "$LEDGER" "USERDATA_WIPE_IMPLICIT_ALLOWED=NO"
require_marker "N0_MINIMUM_GATE" "$LEDGER" "N0_SYS_BOOT_COMPLETED=REQUIRED"
require_marker "N1_REQUIRES_N0" "$LEDGER" "N1_REQUIRES_N0_EVIDENCE=YES"

if [ "$FAILURES" -eq 0 ]; then
  say "TITAN2_N0_N1_FLASH_PLAN_LEDGER_CONTRACT=PASS"
  exit 0
fi

say "TITAN2_N0_N1_FLASH_PLAN_LEDGER_CONTRACT=FAIL"
say "FAILURES=$FAILURES"
exit 1
