#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PROFILE="$ROOT/build/titan2/n1d-c3-composition.env"
TD_GATE="$ROOT/build/gates/n1d-c3-trebledroid-contract.sh"

fail() {
    echo "N1D_C3_PRODUCT_COMPOSITION_CONTRACT=FAIL $*" >&2
    exit 1
}

[[ -f "$PROFILE" ]] || fail "missing_profile=$PROFILE"
[[ -f "$TD_GATE" ]] || fail "missing_trebledroid_gate=$TD_GATE"
bash -n "$PROFILE" "$TD_GATE"

for required in     'N1D_C3_COMPOSITION_VERSION=4'     'N1D_C3_ACTIVE_PHASE=C3A_CONTROL'     'N1D_C3_COMPOSITION_MODE=PINNED_RESTLESS_TREBLEDROID_CONTROL'     'N1D_C3_PRODUCT_NAME=treble_arm64_bvN'     'N1D_C3_PRODUCT_DEVICE=tdgsi_arm64_ab'     'N1D_C3_RELEASE_CONFIG=bp4a'     'N1D_C3_FIRST_BUILD_VARIANT=user'     'N1D_C3_FIRST_BUILD_GOAL=systemimage'     'N1D_C3A_ADD_PROJECT_COUNT=12'     'N1D_C3A_REMOVE_PROJECT_COUNT=54'     'N1D_C3A_RETAINED_GRAPHENE_PROJECT_COUNT=979'     'N1D_C3A_MANAGED_PROJECT_COUNT=991'     'N1D_C3A_CONTROL_PATCH_TIER_COUNT=5'     'N1D_C3A_CONTROL_PATCH_COUNT=369'     'N1D_C3_RELEASE_RUNTIME_PATCH_ALLOWLIST_COUNT=0'     'N1D_C3_HANDCRAFTED_PRODUCT_RETIRED=YES'     'N1D_C3A_RELEASE_ELIGIBLE=NO'     'N1D_C3B_RESTLESS_FULL_PATCH_STACK_ALLOWED=NO'     'N1D_C3B_BUILD_AUTHORIZED=NO_UNTIL_C3A_CONTROL_EVIDENCE'     'N1D_C3_RELEASE_ELIGIBLE=NO'     'N1D_C3_BUILD_AUTHORIZED=NO'     'N1D_C3_COMPOSITION_CONTRACT=PASS'
do
    grep -Fxq "$required" "$PROFILE" || fail "profile_missing=$required"
done

if [[ -d "$ROOT/build/titan2/n1d-c3-product" ]]; then
    fail "retired_handcrafted_product_bundle_present"
fi

bash "$TD_GATE"

echo "N1D_C3_PRODUCT_COMPOSITION_C3A_GRAPH=PASS_991"
echo "N1D_C3_PRODUCT_COMPOSITION_HANDCRAFTED_PATH=PASS_RETIRED"
echo "N1D_C3_PRODUCT_COMPOSITION_TREBLEDROID_REBASELINE=PASS"
echo "N1D_C3_PRODUCT_COMPOSITION_CONTRACT=PASS"
