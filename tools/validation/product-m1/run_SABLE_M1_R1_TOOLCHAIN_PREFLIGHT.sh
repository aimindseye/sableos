#!/usr/bin/env bash
set -u

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)" || exit 90
REPO_ROOT="$(CDPATH= cd -- "$SCRIPT_DIR/../../.." && pwd -P)" || exit 91
SCRIPT="$SCRIPT_DIR/SABLE_M1_R1_TOOLCHAIN_PREFLIGHT.py"
CONTRACT="$REPO_ROOT/product/m1/sable-m1-r1-toolchain-contract-v1.json"

EXPECTED_SCRIPT_SHA256="bdc00d0d18bc6ad9ecfcb6b7f94d3ece564f462e47d0a2ec65305213ed4426fb"
EXPECTED_CONTRACT_SHA256="0e447be147989eadc9d1257800e9f06cec2a93f61c8c7f65d8ffff574d66f1eb"

if [ ! -f "$SCRIPT" ]; then
  echo "M1_R1_SCRIPT_BINDING=FAIL_MISSING"
  exit 92
fi
if [ ! -f "$CONTRACT" ]; then
  echo "M1_R1_CONTRACT_BINDING=FAIL_MISSING"
  exit 93
fi

SCRIPT_HASH_LINE="$(sha256sum -- "$SCRIPT")" || exit 94
CONTRACT_HASH_LINE="$(sha256sum -- "$CONTRACT")" || exit 95
ACTUAL_SCRIPT_SHA256="${SCRIPT_HASH_LINE%% *}"
ACTUAL_CONTRACT_SHA256="${CONTRACT_HASH_LINE%% *}"

echo "EXPECTED_SCRIPT_SHA256=$EXPECTED_SCRIPT_SHA256"
echo "ACTUAL_SCRIPT_SHA256=$ACTUAL_SCRIPT_SHA256"
echo "EXPECTED_CONTRACT_SHA256=$EXPECTED_CONTRACT_SHA256"
echo "ACTUAL_CONTRACT_SHA256=$ACTUAL_CONTRACT_SHA256"

if [ "$ACTUAL_SCRIPT_SHA256" != "$EXPECTED_SCRIPT_SHA256" ]; then
  echo "M1_R1_SCRIPT_BINDING=FAIL_HASH"
  exit 96
fi
if [ "$ACTUAL_CONTRACT_SHA256" != "$EXPECTED_CONTRACT_SHA256" ]; then
  echo "M1_R1_CONTRACT_BINDING=FAIL_HASH"
  exit 97
fi

echo "M1_R1_SCRIPT_BINDING=PASS"
echo "M1_R1_CONTRACT_BINDING=PASS"

env \
  SOURCE_MUTATION_AUTHORIZED=NO \
  WORKSPACE_OUTPUT_MUTATION_AUTHORIZED=NO \
  BUILD_AUTHORIZED=NO \
  BUILD_TOOL_EXECUTION=NO \
  DEVICE_CONTACT_AUTHORIZED=NO \
  DEVICE_REBOOT_AUTHORIZED=NO \
  FLASH_AUTHORIZED=NO \
  SLOT_CHANGE_AUTHORIZED=NO \
  USERDATA_OR_METADATA_WIPE_AUTHORIZED=NO \
  KEY_GENERATION_AUTHORIZED=NO \
  SIGNING_AUTHORIZED=NO \
  OTA_GENERATION_AUTHORIZED=NO \
  DELETE_AUTHORIZED=NO \
  /usr/bin/python3 "$SCRIPT" \
    --repo-root "$REPO_ROOT" \
    --workspace /srv/data/sableos_panther_graphene_2026081300_workspace \
    --contract "$CONTRACT"

RC=$?
echo
echo "SABLE_M1_R1_RUNNER_RC=$RC"
exit "$RC"
